#!/usr/bin/env python3
"""Assembles the variant harness into ../index.html (harness only; delete with the losers).

Each variant lives in variants/<name>/: index.html (the markup inside <body>, no <html>/<head>),
style.css (every rule scoped to html[data-variant="<name>"]) and, optionally, script.js.
Run: python3 variants/build.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
VARIANTS = [  # (folder, picker label), in picker order
    ("note", "Note"),
    ("poster", "Poster"),
    ("terminal", "Terminal"),
    ("steps", "Steps"),
    ("manual", "Manual"),
]

present = [(n, l) for n, l in VARIANTS if (ROOT / "variants" / n / "index.html").exists()]
styles = "\n".join(
    f'  <link rel="stylesheet" href="variants/{n}/style.css" />' for n, _ in present if (ROOT / "variants" / n / "style.css").exists()
)
bodies = "\n".join(
    f'<div class="variant" data-variant-root="{n}" data-variant-label="{l}" hidden>\n'
    + (ROOT / "variants" / n / "index.html").read_text().rstrip()
    + "\n</div>"
    for n, l in present
)
scripts = "\n".join(
    f'<script src="variants/{n}/script.js"></script>' for n, _ in present if (ROOT / "variants" / n / "script.js").exists()
)

html = f"""<!doctype html>
<!-- Generated by variants/build.py from variants/*/. Edit those files, then run python3 variants/build.py. -->
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>Muster: you’re in</title>
  <meta name="description" content="Muster organises the skills Claude Code has on your Mac. It finds them, shows them in one place, and checks them for duplicates and conflicts. Nothing leaves your Mac." />
  <meta name="theme-color" content="#ffffff" />
  <meta property="og:title" content="Muster: you’re in" />
  <meta property="og:description" content="Install Muster with one line: curl -fsSL https://muster.is/install.sh | bash" />
  <meta property="og:type" content="website" />
  <link rel="icon" href="assets/favicon.svg" type="image/svg+xml" />
  <link rel="preconnect" href="https://fonts.googleapis.com" />
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
  <link href="https://fonts.googleapis.com/css2?family=IBM+Plex+Sans+Condensed:wght@400;500&family=Geist:wght@300..600&family=Geist+Mono:wght@400;500&display=swap" rel="stylesheet" />
  <link rel="stylesheet" href="assets/brand.css" />
{styles}
  <link rel="stylesheet" href="variants/picker.css" />
  <script>window.musterVariants = {{}}</script>
</head>
<body>
{bodies}
<script src="assets/site.js"></script>
{scripts}
<script src="variants/picker.js"></script>
</body>
</html>
"""
(ROOT / "index.html").write_text(html)
print(f"index.html: {', '.join(n for n, _ in present) or 'no variants yet'}")
